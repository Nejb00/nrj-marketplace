import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';

const edge = fs.readFileSync('supabase/functions/sign-product-media-uploads/index.ts', 'utf8');
const config = fs.readFileSync('supabase/config.toml', 'utf8');

test('signing endpoint is POST-only and requires a verified admin user JWT', () => {
  assert.match(edge, /req\.method !== "POST"/);
  assert.match(edge, /x-client-info/);
  assert.match(edge, /if \(!isAdmin\(req\)\)/);
  assert.match(edge, /payload\.role !== "authenticated"/);
  assert.match(edge, /payload\.is_anonymous === true/);
  assert.match(edge, /payload\.app_metadata/);
  assert.match(edge, /role === "admin"/);
});

test('signing endpoint rejects missing, non-integer, zero and more than six slots', () => {
  assert.match(edge, /Number\.isInteger\(count\)/);
  assert.match(edge, /count < 1/);
  assert.match(edge, /count > 6/);
  assert.match(edge, /typeof count !== "number"/);
});

test('public IDs are generated by the server below the fixed NRJ product prefix', () => {
  assert.match(edge, /crypto\.randomUUID\(\)/);
  assert.match(edge, /nrj-marketplace\/products\//);
  assert.match(edge, /const publicId = PRODUCT_PREFIX \+ batchId \+ "\/" \+ slot/);
  assert.doesNotMatch(edge, /body\?\.public_id|body\?\.publicId/);
});

test('signing response exposes only public Cloudinary data, never the API secret', () => {
  assert.match(edge, /cloud_name:\s*CLOUDINARY_CLOUD_NAME/);
  assert.match(edge, /api_key:\s*CLOUDINARY_API_KEY/);
  assert.match(edge, /batch_id:\s*batchId/);
  assert.match(edge, /upload_preset:\s*UPLOAD_PRESET/);
  assert.match(edge, /uploads/);
  assert.match(edge, /signature/);
  assert.doesNotMatch(edge, /api_secret\s*:/i);
  assert.doesNotMatch(edge, /CLOUDINARY_API_SECRET\s*[,}]/);
});

test('upload signatures contain only sorted overwrite, public_id, timestamp and upload_preset', () => {
  assert.match(edge, /overwrite:\s*"false"/);
  assert.match(edge, /public_id:\s*publicId/);
  assert.match(edge, /timestamp/);
  assert.match(edge, /upload_preset:\s*UPLOAD_PRESET/);
  assert.match(edge, /\.sort\(\(\[a\], \[b\]\) => a\.localeCompare\(b\)\)/);
  assert.match(edge, /encodeSignatureParams\(signedParams\) \+ CLOUDINARY_API_SECRET/);
});

test('missing Cloudinary secrets or upload preset fail closed', () => {
  assert.match(edge, /CLOUDINARY_PRODUCT_UPLOAD_PRESET/);
  assert.match(edge, /if \(!CLOUDINARY_CLOUD_NAME \|\| !CLOUDINARY_API_KEY \|\| !CLOUDINARY_API_SECRET \|\| !UPLOAD_PRESET\)/);
});

test('Supabase gateway JWT verification is enabled for the signing endpoint', () => {
  assert.match(config, /\[functions\.sign-product-media-uploads\][\s\S]*?verify_jwt = true/);
});
